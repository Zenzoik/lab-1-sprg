static i2c_bus_t g_i2c;
static spi_bus_t g_spi;
static app_ports_t g_ports;

void platform_init(void) {
  g_i2c = k_i2c;
  g_i2c.ctx = BOARD_I2C;
  g_spi = k_spi;
  g_spi.ctx = BOARD_SPI;

  /* ADC: self-calibration (RM0490: required once after power-up, before the first conversion). */
  (void)HAL_ADCEx_Calibration_Start(BOARD_ADC);

  /* Servo outputs start centred. */
  (void)HAL_TIM_PWM_Start(BOARD_PWM_TIM, TIM_CHANNEL_1);
  (void)HAL_TIM_PWM_Start(BOARD_PWM_TIM, TIM_CHANNEL_2);
  pwm_set_us(1, 1500);
  pwm_set_us(2, 1500);

  /* Idle levels: CS# high, marker low, LED off. */
  spi_cs(NULL, 1);
  marker(0);
  led_write(0);

  /* LR3 service pins: stimulus (idle high = button released) and three logic analyzer probes. */
  GPIO_InitTypeDef gi = {0};
  gi.Mode = GPIO_MODE_OUTPUT_PP;
  gi.Pull = GPIO_NOPULL;
  gi.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_WritePin(BOARD_STIM_PORT, BOARD_STIM_PIN, GPIO_PIN_SET);
  gi.Pin = BOARD_STIM_PIN;
  HAL_GPIO_Init(BOARD_STIM_PORT, &gi);
  for (unsigned ch = 0; ch < 3u; ch++) {
    probe_write(ch, 0);
  }
  gi.Pin = BOARD_PROBE0_PIN | BOARD_PROBE1_PIN;
  HAL_GPIO_Init(GPIOB, &gi);
  gi.Pin = BOARD_PROBE2_PIN;
  HAL_GPIO_Init(GPIOA, &gi);
  HAL_NVIC_SetPriority(EXTI4_15_IRQn, 1, 0);
  HAL_NVIC_EnableIRQ(EXTI4_15_IRQn);
  btn_mode_set(1);

  g_ports = (app_ports_t){
      .i2c = &g_i2c,
      .spi = &g_spi,
      .write = uart_write,
      .read_char = uart_read_char,
      .millis = clock_millis,
      .delay_ms = clock_delay_ms,
      .i2c_last_error = i2c_last_error,
      .i2c_status_reg = i2c_status_reg,
      .adc_read = adc_read,
      .button_pressed = button_pressed,
      .led_write = led_write,
      .marker = marker,
      .pwm_set_us = pwm_set_us,
      .pwm_get_us = pwm_get_us,
      .spi_set_mode = spi_set_mode,
      .cycles = cycles_now,
      .cycles_per_us = BOARD_CORE_MHZ,
      .probe = probe_write,
      .button_event = button_event,
      .btn_mode_set = btn_mode_set,
      .stim_set = stim_set,
      .stim_press = stim_press,
      .uart_rx_stats = uart_rx_stats,
      .stack_used = stack_used,
      .stack_size = stack_size,
      .heap_used = heap_used,
      .reboot = reboot,
  };
}

const app_ports_t *platform_ports(void) {
  return &g_ports;
}
